use regress::Regex;
use crate::atom::Atom;

pub enum Expr<'a> {
    Bool(bool),
    Null,
    Undefined,
    Float(f64),
    Int32(i32),
    String(Atom),
    BigInt(Atom),
    RegExp(&'a Regex),
    Template(&'a TemplateLiteral<'a>),
    Ident(Atom),
    MetaProp(&'a MetaProp),
    Super(&'a SuperProp),
    ArrayLit(&'a ArrayLiteral<'a>),
    ArrowFunction(&'a ArrowFunction<'a>),
    Assignment(&'a AssignmentExpression<'a>),
    Await(&'a AwaitExpression<'a>),
    Binary(&'a BinaryExpression<'a>),
    Call(&'a CallExpression<'a>),
    Chain(&'a ChainExpression<'a>),
    Class(&'a ClassExpression<'a>),
    Conditional(&'a ConditionalExpression<'a>),
    Function(&'a FunctionExpression<'a>),
    Import(&'a ImportExpression<'a>),
    Logical(&'a LogicalExpression<'a>),
    New(&'a NewExpression<'a>),
    Object(&'a ObjectExpression<'a>),
    Sequence(&'a SequenceExpression<'a>),
    TaggedTemplate(&'a TaggedTemplateExpression<'a>),
    This,
    Unary(&'a UnaryExpression<'a>),
    Update(&'a UpdateExpression<'a>),
    Yield(&'a YieldExpression<'a>),
    PrivateIn(&'a PrivateInExpression<'a>),
    Member(&'a MemberExpression<'a>),
    ComputedMember(&'a ComputedMemberExpression<'a>),
    PrivateField(&'a PrivateFieldExpression<'a>),
}
