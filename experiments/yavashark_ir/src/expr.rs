use bumpalo::boxed::Box;
use num_bigint::BigInt;
use regress::Regex;
use yavashark_string::YSString;

pub enum Expression<'alloc> {
    Bool(bool),
    Null,
    Undefined,
    Float(f64),
    Int32(i32),
    String(YSString),
    BigInt(&'alloc BigInt),
    RegExp(&'alloc Regex),
    Template(&'alloc TemplateLiteral<'alloc>),
    Ident(YSString),
    MetaProp(&'alloc MetaProp),
    Super(&'alloc SuperProp),
    ArrayLit(&'alloc ArrayLiteral<'alloc>),
    ArrowFunction(&'alloc ArrowFunction<'alloc>),
    Assignment(&'alloc AssignmentExpression<'alloc>),
    Await(&'alloc AwaitExpression<'alloc>),
    Binary(&'alloc BinaryExpression<'alloc>),
    Call(&'alloc CallExpression<'alloc>),
    Chain(&'alloc ChainExpression<'alloc>),
    Class(&'alloc ClassExpression<'alloc>),
    Conditional(&'alloc ConditionalExpression<'alloc>),
    Function(&'alloc FunctionExpression<'alloc>),
    Import(&'alloc ImportExpression<'alloc>),
    Logical(&'alloc LogicalExpression<'alloc>),
    New(&'alloc NewExpression<'alloc>),
    Object(&'alloc ObjectExpression<'alloc>),
    Sequence(&'alloc SequenceExpression<'alloc>),
    TaggedTemplate(&'alloc TaggedTemplateExpression<'alloc>),
    This,
    Unary(&'alloc UnaryExpression<'alloc>),
    Update(&'alloc UpdateExpression<'alloc>),
    Yield(&'alloc YieldExpression<'alloc>),
    PrivateIn(&'alloc PrivateInExpression<'alloc>),
    Member(&'alloc MemberExpression<'alloc>),
    ComputedMember(&'alloc ComputedMemberExpression<'alloc>),
    PrivateField(&'alloc PrivateFieldExpression<'alloc>),
}
